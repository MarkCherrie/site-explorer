"""Convert the Database of British and Irish Hills (DoBIH) CSV into a compact JS data file for the
explorer (loaded with a <script> tag, so it works from file://).

Each hill keeps: longitude, latitude, height (m), drop / prominence (m), its best-known class, and its
name (alternative names in square brackets are kept as a second name).

Source: The Database of British and Irish Hills v18.6, https://www.hills-database.co.uk (CC BY 4.0).

Usage:
  python3 viewer/tools/build_hills.py DoBIH_v18_6.csv viewer/data/hills.js
"""
import csv
import json
import re
import sys

# best-known class first: the first one a hill belongs to is shown on its label
CLASSES = [("M", "Munro"), ("C", "Corbett"), ("G", "Graham"), ("D", "Donald"), ("Hew", "Hewitt"),
           ("Ma", "Marilyn"), ("Hu", "HuMP"), ("Sim", "Simm")]

src, out = sys.argv[1], sys.argv[2]
rows = [{k.strip(): (v or "").strip() for k, v in r.items()} for r in csv.DictReader(open(src, encoding="utf-8-sig"))]

hills = []
for r in rows:
    try:
        lat, lon, m = float(r["Latitude"]), float(r["Longitude"]), float(r["Metres"])
    except ValueError:
        continue
    drop = float(r["Drop"] or 0)
    cls = next((i for i, (k, _) in enumerate(CLASSES) if r.get(k) == "1"), -1)
    name = re.sub(r"\s+", " ", r["Name"])
    # "Ben Nevis [Beinn Nibheis]" → main + alternative; brackets can also sit mid-name
    main = re.sub(r"\s*\[[^\]]*\]?", "", name).strip() or name
    alt = "; ".join(a.strip() for a in re.findall(r"\[([^\]]*)\]?", name) if a.strip())
    hills.append([round(lon, 5), round(lat, 5), round(m), round(drop), cls, main] + ([alt] if alt else []))

payload = {
    "source": "The Database of British and Irish Hills v18.6 (CC BY 4.0), hills-database.co.uk",
    "classes": [label for _, label in CLASSES],
    "fields": ["lon", "lat", "metres", "drop", "class index (-1 none)", "name", "alternative name (optional)"],
    "hills": hills,
}
with open(out, "w") as fh:
    fh.write("// Generated by viewer/tools/build_hills.py — Database of British and Irish Hills v18.6 (CC BY 4.0)\n")
    fh.write("window.HILLS = " + json.dumps(payload, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(f"{len(hills)} hills -> {out}")
