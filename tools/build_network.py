"""Cut the OpenStreetMap power network for Scotland (from the insights project) into 1° tiles the
explorer loads on demand with <script> tags (works from file:// and on the published site).

Inputs (both © OpenStreetMap contributors, ODbL; built in the insights project):
  insights/scripts/osm/osm_power_lines.geojson   power=line, minor_line and cable, with voltage tags
  insights/app/src/lib/substations.json          substations with a tier (transmission, bsp, primary,
                                                 secondary, unclassified)

Each tile holds the lines whose bounding box touches it (a line can sit in several tiles; the page
drops repeats by id) and the substations inside it. Line coordinates are integers of 1e-5° (~1 m),
the first point absolute and the rest as differences, to keep the files small.

Usage:
  python3 viewer/tools/build_network.py ../insights/scripts/osm/osm_power_lines.geojson \
      ../insights/app/src/lib/substations.json viewer/data/network
"""
import json
import math
import os
import sys
from collections import defaultdict

lines_src, subs_src, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
TIERS = ["secondary", "primary", "bsp", "transmission", "unclassified"]


def kv_of(tag):   # highest voltage in an OSM voltage tag, in kV ("33000;11000" -> 33)
    best = 0
    for part in str(tag or "").replace(",", ";").split(";"):
        try:
            best = max(best, float(part.strip()) / 1000)
        except ValueError:
            pass
    return best


def band(kv, power):   # 0: ≤22 kV, 1: 33 kV, 2: 132 kV, 3: 275 kV, 4: 400 kV
    if kv <= 0:
        return 0 if power in ("minor_line", "cable") else 2
    return 0 if kv <= 22 else 1 if kv <= 66 else 2 if kv <= 200 else 3 if kv <= 330 else 4


tiles = defaultdict(lambda: {"lines": [], "subs": []})
lines = json.load(open(lines_src))["features"]
for i, f in enumerate(lines):
    g, p = f.get("geometry") or {}, f.get("properties") or {}
    if g.get("type") != "LineString" or len(g["coordinates"]) < 2:
        continue
    power = p.get("power")
    if power not in ("line", "minor_line", "cable"):
        continue
    cable = 1 if power == "cable" or p.get("location") in ("underground", "underwater") else 0
    q = [(round(x * 1e5), round(y * 1e5)) for x, y in g["coordinates"][:]]
    flat = [q[0][0], q[0][1]]
    for (x0, y0), (x1, y1) in zip(q, q[1:]):
        flat += [x1 - x0, y1 - y0]
    rec = [p.get("id", i), band(kv_of(p.get("voltage")), power), cable, round(kv_of(p.get("voltage"))), flat]
    xs = [c[0] for c in g["coordinates"]]; ys = [c[1] for c in g["coordinates"]]
    for ty in range(math.floor(min(ys)), math.floor(max(ys)) + 1):
        for tx in range(math.floor(min(xs)), math.floor(max(xs)) + 1):
            tiles[f"{ty}_{tx}"]["lines"].append(rec)
subs = json.load(open(subs_src))["features"]
for f in subs:
    x, y = f["geometry"]["coordinates"][:2]
    tier = (f.get("properties") or {}).get("tier", "unclassified")
    tiles[f"{math.floor(y)}_{math.floor(x)}"]["subs"].append([round(x, 5), round(y, 5), TIERS.index(tier) if tier in TIERS else 4])

os.makedirs(outdir, exist_ok=True)
total = 0
for key, t in tiles.items():
    body = json.dumps(t, separators=(",", ":"))
    with open(os.path.join(outdir, f"net_{key}.js"), "w") as fh:
        fh.write(f'(window.NET_TILES = window.NET_TILES || {{}})["{key}"] = {body};\n')
    total += len(body)
with open(os.path.join(outdir, "net_index.js"), "w") as fh:
    fh.write("// Generated by viewer/tools/build_network.py — OpenStreetMap power network (ODbL), 1° tiles\n")
    fh.write("window.NET_INFO = " + json.dumps({"tiers": TIERS, "bands": ["≤22 kV", "33 kV", "132 kV", "275 kV", "400 kV"],
                                                "tiles": sorted(tiles)}, separators=(",", ":")) + ";\n")
print(f"{len(lines)} lines, {len(subs)} substations -> {len(tiles)} tiles, {total / 1e6:.1f} MB -> {outdir}")
