"""Convert the UK OpenStreetMap wind turbines from the countingTurbnies project into a small JS
data file for the explorer (loaded with a <script> tag, so it works from file://).

All turbines are kept (onshore and offshore); the explorer lets you choose between this OSM set
and DeepOWT. The source GeoJSON is produced by countingTurbnies/scripts/fetch_turbines.mjs
(Overpass; small domestic turbines already dropped).

Usage:
  python3 viewer/tools/build_osm_onshore.py \
      /Volumes/1TB/working/countingTurbnies/data/turbines.geojson viewer/data/osm_turbines.js

Data © OpenStreetMap contributors, ODbL.
"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
features = json.load(open(src))["features"]

flat = []   # [lon, lat, tip_m (0 = unknown), offshore (0/1), ...]
offshore = 0
for f in features:
    p = f.get("properties") or {}
    lon, lat = f["geometry"]["coordinates"][:2]
    off = 1 if p.get("offshore") else 0
    offshore += off
    flat += [round(lon, 5), round(lat, 5), round(p.get("tip") or 0), off]

payload = {
    "source": "OpenStreetMap wind turbines (UK) via countingTurbnies/scripts/fetch_turbines.mjs",
    "license": "ODbL — © OpenStreetMap contributors",
    "count": len(features),
    "offshore": offshore,
    "fields": ["lon", "lat", "tip_m", "offshore"],
    "points": flat,
}
with open(out, "w") as fh:
    fh.write("// Generated by viewer/tools/build_osm_onshore.py — UK wind turbines from OpenStreetMap\n")
    fh.write("window.OSM_TURBINES = " + json.dumps(payload, separators=(",", ":")) + ";\n")
print(f"{payload['count']} turbines ({offshore} flagged offshore) -> {out}")
