"""Cut the GHSL 2025 population grid (30 arc-second cells, about 1 km) into small tiles the explorer
can load with <script> tags (so it works from file:// as well as on the web).

Source: GHS-POP R2023A, epoch 2025, WGS84 30 arc-seconds — European Commission, Joint Research Centre
(CC BY 4.0). https://human-settlement.emergency.copernicus.eu/download.php?ds=pop

1. Download and crop to Europe with GDAL (writes raw float32 people-per-cell + an ENVI header):
     curl -L -o ghs_pop.zip "https://jeodpp.jrc.ec.europa.eu/ftp/jrc-opendata/GHSL/GHS_POP_GLOBE_R2023A/GHS_POP_E2025_GLOBE_R2023A_4326_30ss/V1-0/GHS_POP_E2025_GLOBE_R2023A_4326_30ss_V1_0.zip"
     unzip ghs_pop.zip GHS_POP_E2025_GLOBE_R2023A_4326_30ss_V1_0.tif
     gdal_translate -projwin -25 72 45 27 -of ENVI -ot Float32 GHS_POP_E2025_GLOBE_R2023A_4326_30ss_V1_0.tif europe.bil
2. Build the tiles:
     python3 viewer/tools/build_population.py europe.bil viewer/data/pop

Each tile is TILE × TILE cells, stored as one byte per cell on a log scale, q = round(ln(1 + people) × SCALE)
(about ±2% error), zlib-compressed and base64-encoded. Tiles that are all zero (sea) are skipped.
"""
import base64
import json
import os
import re
import sys
import zlib

import numpy as np

TILE, SCALE = 600, 23.0

src, outdir = sys.argv[1], sys.argv[2]
hdr = open(os.path.splitext(src)[0] + ".hdr").read()
cols = int(re.search(r"samples\s*=\s*(\d+)", hdr).group(1))
rows = int(re.search(r"lines\s*=\s*(\d+)", hdr).group(1))
info = re.search(r"map info = \{[^,]+,\s*1,\s*1,\s*([-\d.]+),\s*([-\d.]+),\s*([\d.]+),\s*([\d.]+)", hdr)
lon0, lat0, resx, resy = (float(info.group(i)) for i in range(1, 5))

grid = np.fromfile(src, dtype="<f4").reshape(rows, cols)
grid = np.nan_to_num(grid, nan=0.0)
grid[grid < 0] = 0
q = np.clip(np.rint(np.log1p(grid) * SCALE), 0, 255).astype(np.uint8)

os.makedirs(outdir, exist_ok=True)
tiles, total_bytes = [], 0
for ti in range(0, (rows + TILE - 1) // TILE):
    for tj in range(0, (cols + TILE - 1) // TILE):
        block = np.zeros((TILE, TILE), dtype=np.uint8)
        part = q[ti * TILE:(ti + 1) * TILE, tj * TILE:(tj + 1) * TILE]
        block[:part.shape[0], :part.shape[1]] = part
        if not block.any():
            continue
        key = f"{ti}_{tj}"
        b64 = base64.b64encode(zlib.compress(block.tobytes(), 9)).decode()
        with open(os.path.join(outdir, f"pop_{key}.js"), "w") as fh:
            fh.write(f'(window.POP_TILES = window.POP_TILES || {{}})["{key}"] = "{b64}";\n')
        tiles.append(key)
        total_bytes += len(b64)

meta = {"source": "GHS-POP R2023A, epoch 2025, 30 arc-seconds — European Commission JRC (CC BY 4.0)",
        "lon0": lon0, "lat0": lat0, "res": resx, "tile": TILE, "scale": SCALE,
        "rows": rows, "cols": cols, "tiles": tiles}
with open(os.path.join(outdir, "pop_index.js"), "w") as fh:
    fh.write("// Generated by viewer/tools/build_population.py — index of GHSL population tiles\n")
    fh.write("window.POP_INFO = " + json.dumps(meta, separators=(",", ":")) + ";\n")
europe = float(grid.sum())
print(f"{len(tiles)} tiles, {total_bytes / 1e6:.1f} MB total; {europe / 1e6:.0f} million people in the crop -> {outdir}")
