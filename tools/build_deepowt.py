"""Convert DeepOWT point locations (Zenodo record 23160399, CC-BY-4.0) into a small JS
data file the explorer can load with a <script> tag (works from file://).

Usage:
  curl -L -o DeepOWT_pnt_locations.parquet \
    "https://zenodo.org/api/records/23160399/files/DeepOWT_pnt_locations.parquet/content"
  python3 viewer/tools/build_deepowt.py DeepOWT_pnt_locations.parquet viewer/data/deepowt_locations.js

Requires: duckdb (pip install duckdb)
"""
import json
import sys

import duckdb

src, out = sys.argv[1], sys.argv[2]
con = duckdb.connect()
con.sql("INSTALL spatial; LOAD spatial;")
rows = con.sql(f"""
    SELECT unit_id, ST_X(geometry) AS lon, ST_Y(geometry) AS lat
    FROM '{src}' WHERE geometry IS NOT NULL ORDER BY unit_id
""").fetchall()

# Flat array [lon, lat, farm, ...]; farm = numeric prefix of unit_id ("0123_4" -> 123)
flat = []
for unit_id, lon, lat in rows:
    farm = int(unit_id.split("_")[0]) if unit_id and unit_id.split("_")[0].isdigit() else -1
    flat += [round(lon, 5), round(lat, 5), farm]

payload = {
    "source": "DeepOWT v5.25.1, Zenodo record 23160399",
    "url": "https://zenodo.org/records/23160399",
    "license": "CC-BY-4.0",
    "count": len(rows),
    "fields": ["lon", "lat", "farm"],
    "points": flat,
}
with open(out, "w") as f:
    f.write("// Generated by viewer/tools/build_deepowt.py — DeepOWT offshore wind turbine locations\n")
    f.write("window.DEEPOWT = " + json.dumps(payload, separators=(",", ":")) + ";\n")
print(f"{len(rows)} points -> {out}")
